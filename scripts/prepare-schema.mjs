import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { parse } from 'yaml';

// Add examples through the plugin's supported OpenAPI extension; leave the upstream snapshot intact.
const document = parse(await readFile(new URL('../schemas/pokeapi.yml', import.meta.url), 'utf8'));
const templates = await Promise.all(
  [
    { lang: 'sh', label: 'cURL', file: 'request.sh' },
    { lang: 'python', label: 'Python HTTP (standard library)', file: 'request.py' },
    { lang: 'php', label: 'PHP (cURL extension)', file: 'request.php' },
  ].map(async ({ file, ...sample }) => ({
    ...sample,
    source: await readFile(new URL(`./snippets/${file}`, import.meta.url), 'utf8'),
  })),
);

const pokebaseEndpoints = JSON.parse(await readFile(new URL('./pokebase-endpoints.json', import.meta.url), 'utf8'));
const pokebaseTemplate = await readFile(new URL('./snippets/request-pokebase.py', import.meta.url), 'utf8');
let count = 0;
let pokebaseCount = 0;
for (const [path, pathItem] of Object.entries(document.paths)) {
  const operation = pathItem.get;
  if (!operation) continue;

  const parameters = [...(pathItem.parameters ?? []), ...(operation.parameters ?? [])];
  // All path parameters in this snapshot accept a numeric resource ID. Use 1 as a concrete example.
  const examplePath = path.replace(/\{([^}]+)\}/g, (_, name) => {
    if (!parameters.some((parameter) => parameter.in === 'path' && parameter.name === name)) {
      throw new Error(`Missing path parameter ${name} in ${operation.operationId}`);
    }
    return '1';
  });
  const url = new URL(examplePath, document.servers[0].url);
  // Only include pagination when declared. In particular, omit the public API's unsupported q filter.
  for (const [name, value] of [['limit', '20'], ['offset', '0']]) {
    if (parameters.some((parameter) => parameter.in === 'query' && parameter.name === name)) {
      url.searchParams.set(name, value);
    }
  }

  // The plugin uses authored samples instead of autogenerated ones, so include cURL as well.
  operation['x-codeSamples'] = templates.map(({ source, ...sample }) => ({
    ...sample,
    source: source.replaceAll('__REQUEST_URL__', url.href),
  }));
  // Pokebase lists fetch all resources, so do not present them as equivalent paginated calls.
  const detail = path.match(/^\/api\/v2\/([^/]+)\/\{id\}\/$/);
  if (detail && pokebaseEndpoints.includes(detail[1])) {
    operation['x-codeSamples'].splice(2, 0, {
      lang: 'python',
      label: 'Python — Pokébase',
      source: pokebaseTemplate.replaceAll('__POKEBASE_ENDPOINT__', detail[1]),
    });
    pokebaseCount++;
  }
  count++;
}

const directory = new URL('../.generated/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL('pokeapi.json', directory), JSON.stringify(document, null, 2) + '\n');
console.log(`Prepared HTTP examples for ${count} operations and Pokébase examples for ${pokebaseCount} supported detail operations.`);
